export type CmpDictionary = (typeof dictionaries)[CmpLocale];

export function getCmpDictionary(locale: CmpLocale): CmpDictionary {
  return dictionaries[locale];
}

type CmpI18nContextValue = {
  locale: CmpLocale;
  dictionary: CmpDictionary;
  localizedPath: (pathname: string) => string;
  setLocale: (locale: CmpLocale) => void;
};

const defaultI18nContext: CmpI18nContextValue = {
  locale: defaultLocale,
  dictionary: dictionaries["en-US"],
  localizedPath: (pathname) => buildLocalizedPath(pathname, defaultLocale),
  setLocale: () => {},
};
const CmpI18nContext = createContext<CmpI18nContextValue>(defaultI18nContext);

function normalizeClientLocale(value?: string | null): CmpLocale {
  return value === "zh-CN" || value?.startsWith("zh") ? "zh-CN" : "en-US";
}

function readCookie(name: string) {
  return document.cookie
    .split("; ")
    .find((item) => item.startsWith(`${name}=`))
    ?.slice(name.length + 1);
}

function persistLocale(locale: CmpLocale) {
  const isProductionDomain = window.location.hostname.endsWith(".superfx.cn");
  document.cookie = `${localeCookieName}=${locale}; path=/; max-age=31536000; SameSite=Lax${
    isProductionDomain ? "; Domain=.superfx.cn" : ""
  }`;
  window.localStorage.setItem(legacyLocaleStorageKey, locale);
}

export function CmpI18nProvider({
  children,
  initialLocale,
}: {
  children: ReactNode;
  initialLocale?: CmpLocale;
}) {
  const [locale, setLocale] = useState<CmpLocale>(initialLocale ?? "en-US");

  useEffect(() => {
    if (initialLocale) {
      return;
    }
    setLocale(
      normalizeClientLocale(
        readCookie(localeCookieName) ??
          window.localStorage.getItem(legacyLocaleStorageKey)
      )
    );
  }, [initialLocale]);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<CmpI18nContextValue>(
    () => ({
      locale,
      dictionary: dictionaries[locale],
      localizedPath: (pathname) => buildLocalizedPath(pathname, locale),
      setLocale: (nextLocale) => {
        setLocale(nextLocale);
        persistLocale(nextLocale);
        void api.updatePreferredLocale(nextLocale).catch(() => {});
      },
    }),
    [locale]
  );

  return (
    <CmpI18nContext.Provider value={value}>{children}</CmpI18nContext.Provider>
  );
}

export function useCmpI18n() {
  return useContext(CmpI18nContext);
}
